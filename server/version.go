package main

// CoreVersion 是 CyanNVR 的**核心版本**（x.y.z），代表应用自身的功能/修复状态。
//
// 它与 **FPK 打包版本**是分离的两件事：
//   - 核心版本：本常量，由 fpk/build-fpk.sh 按源码变更范围自动 bump
//   - FPK 版本：飞牛安装包版本，格式 x.y.z-r，其中 x.y.z 取自本常量，
//     r 是打包修订号，同一核心版本下每次打包自动 +1
//
// 自动 bump 规则（打包时判定，无需手工维护本文件）：
//   - 只动 fpk/            -> patch +1（改向导、图标、生命周期脚本等）
//   - 动了 server/、web/   -> minor +1（功能或修复改动）
//   - 大改动               -> 打包时加 --bump=major，第一位 +1
//   - 源码无变化           -> 核心版本不变，只递增 r 重新出包
//
// 因此同一个核心版本可能对应多个 FPK 包（1.7.0-1、1.7.0-2 …），
// 用于「代码没变但需要重新出包」的场景。
//
// 核心版本变化时，打包脚本会自动把修订号 r 重置为 1。
//
// 注意：本文件被 build-fpk.sh 写入，且被排除在「变更判定」的哈希之外
// （否则每次打包都会自我触发 bump）。
const CoreVersion = "1.7.0"
