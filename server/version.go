package main

// CoreVersion 是 CyanNVR 的**核心版本**（x.y.z），代表应用自身的功能/修复状态。
//
// 它与 **FPK 打包版本**是分离的两件事：
//   - 核心版本：功能或修复改动时，手动更新这里
//   - FPK 版本：飞牛安装包版本，格式 x.y.z-r，其中 x.y.z 取自本常量，
//     r 是打包修订号，由 fpk/build-fpk.sh 每次打包自动 +1
//
// 因此同一个核心版本可能对应多个 FPK 包（1.0.0-1、1.0.0-2 …），
// 用于「代码没变但需要重新出包」的场景（改图标、改向导、改生命周期脚本等）。
//
// 修改本常量后，fpk 打包脚本会自动把修订号重置为 1。
const CoreVersion = "1.5.0"
