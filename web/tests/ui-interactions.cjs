const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const out = process.env.QA_OUTPUT || '../ui-test';
fs.mkdirSync(out, { recursive: true });
let browser;
(async () => {
  browser = await chromium.launch({ channel: 'msedge', headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, timezoneId: 'Asia/Shanghai' });
  await context.addInitScript(() => {
    localStorage.setItem('nvr_demo_mode', '1');
    localStorage.setItem('nvr_token', 'demo');
    localStorage.setItem('nvr_user', JSON.stringify({id:'local',username:'admin',role:'admin'}));
    localStorage.setItem('nvr_settings_local', JSON.stringify({theme:'light',fontSize:'normal',careMode:false,demoMode:true}));
  });
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.route(/^http:\/\/127\.0\.0\.1:5173\/api\//, route => route.fulfill({status:503,contentType:'application/json',body:'{}'}));
  const check = (condition, message) => { assert(condition, message); console.log('PASS '+message); };
  await page.goto('http://127.0.0.1:5173/#/settings');
  const care = page.locator('.van-cell').filter({has:page.locator('.van-cell__title').filter({hasText:/^关怀模式/})}).getByRole('switch');
  await care.click();
  check(await page.locator('.font-opts').count() === 0, 'care mode hides font controls');
  await page.screenshot({path:out+'/desktop-settings-care.png'});
  await care.click();
  await page.getByRole('button',{name:'特大字体',exact:true}).click();
  check(await page.getByRole('button',{name:'特大字体',exact:true}).getAttribute('aria-pressed') === 'true', 'font choice exposes selected state');
  await care.click();
  check(await page.evaluate(()=>getComputedStyle(document.documentElement).getPropertyValue('--nvr-font-scale').trim()) === '1','care font ignores saved font size');
  await care.click();
  check(await page.getByRole('button',{name:'特大字体',exact:true}).getAttribute('aria-pressed') === 'true','font preference restored after care');
  await page.getByRole('button',{name:'标准字体',exact:true}).click();
  await page.getByRole('button',{name:'选择保留天数',exact:true}).click();
  const picker = page.locator('.van-popup:visible .van-picker');
  await picker.waitFor();
  await page.waitForTimeout(350);
  const column = picker.locator('.van-picker-column').first();
  const selected = () => column.locator('.van-picker-column__item--selected').innerText();
  check((await selected()).includes('30'),'picker starts at saved value');
  await column.hover(); await page.mouse.wheel(0,120); await page.waitForTimeout(250);
  check((await selected()).includes('90'),'mouse wheel changes option');
  const rect = await column.boundingBox();
  await page.mouse.move(rect.x+rect.width/2,rect.y+rect.height/2);
  await page.mouse.down(); await page.mouse.move(rect.x+rect.width/2,rect.y+rect.height/2-65,{steps:5}); await page.mouse.up();
  await page.waitForTimeout(250);
  check(!(await selected()).includes('90'),'mouse drag changes option');
  await page.screenshot({path:out+'/desktop-picker.png'});
  await picker.getByRole('button',{name:'取消',exact:true}).click();
  check(await page.locator('.days-input input').first().inputValue() === '30','cancel discards picker changes');
  await page.getByRole('button',{name:'选择保留天数',exact:true}).click();
  await column.hover(); await page.mouse.wheel(0,120); await page.waitForTimeout(250);
  await picker.getByRole('button',{name:'确认',exact:true}).click();
  check(await page.locator('.days-input input').first().inputValue() === '90','confirm applies picker value');
  await page.getByText('定时录制',{exact:true}).click();
  await page.getByRole('button',{name:'录像开始时间',exact:true}).click();
  const timePicker = page.locator('.van-popup:visible .van-picker');
  await timePicker.locator('.van-picker-column').first().hover();
  await page.mouse.wheel(0,120); await page.waitForTimeout(250);
  await timePicker.getByRole('button',{name:'确认',exact:true}).click();
  check((await page.getByRole('button',{name:'录像开始时间',exact:true}).innerText()).includes('09:00'),'time picker confirms structured value');
  await page.locator('.nav-item[href="#/playback"]').click();
  await page.locator('.seg-time:visible').first().waitFor();
  await page.getByRole('button',{name:'暂停回放',exact:true}).click();
  const pausedTime = await page.locator('.timeline .current').innerText();
  await page.waitForTimeout(700);
  check(await page.locator('.timeline .current').innerText() === pausedTime,'pause freezes playback clock');
  const time = await page.locator('.player .time').innerText();
  check(time.endsWith(pausedTime),'video and timeline show same local time');
  await page.getByRole('button',{name:'4倍速',exact:true}).click();
  check(await page.getByRole('button',{name:'4倍速',exact:true}).getAttribute('aria-pressed')==='true','speed selection updates');
  const segment = page.locator('.seg-time:visible').first();
  const start = (await segment.innerText()).split('-')[0];
  await segment.click();
  check((await page.locator('.timeline .current').innerText()).startsWith(start),'segment selection seeks to segment');
  const seekTarget = start.slice(0,5)+':10';
  await page.locator('#playback-time').fill(seekTarget);
  await page.getByRole('button',{name:'跳转',exact:true}).click();
  check(await page.locator('.timeline .current').innerText() === seekTarget,'time input seeks exact second');
  const slider = page.getByRole('slider',{name:'录像时间轴'});
  await slider.focus(); await page.keyboard.press('ArrowRight');
  const afterKey = await slider.getAttribute('aria-valuenow');
  check(Number(afterKey) > Number(start.slice(0,2))*3600+Number(start.slice(3,5))*60+10,'keyboard seeks timeline');
  await page.screenshot({path:out+'/desktop-playback.png'});
  await page.locator('.nav-item[href="#/events"]').click();
  await page.getByText('筛选设备与日期',{exact:true}).click();
  await page.getByRole('textbox',{name:'筛选日期',exact:true}).click();
  const datePicker = page.locator('.van-popup:visible .van-picker');
  const year = datePicker.locator('.van-picker-column').first();
  await year.hover(); await page.mouse.wheel(0,-120); await page.waitForTimeout(250);
  await datePicker.getByRole('button',{name:'确认',exact:true}).click();
  await page.getByText('暂无事件',{exact:true}).waitFor();
  check(await page.getByText('筛选设备与日期',{exact:true}).isVisible(),'filter remains available for empty results');
  await page.getByRole('button',{name:'清除筛选',exact:true}).last().click();
  await page.locator('.ev-card').first().waitFor();
  check(true,'clear filter recovers event list');
  await page.setViewportSize({width:390,height:850});
  await page.goto('http://127.0.0.1:5173/#/settings');
  await care.click();
  await page.screenshot({path:out+'/mobile-settings-care.png'});
  check(errors.length===0,'no unhandled page errors: '+errors.join(','));
  await browser.close();
})().catch(e=>{console.error(e);process.exitCode=1;}).finally(async()=>{await browser?.close()});
